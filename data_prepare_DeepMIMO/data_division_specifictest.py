"""Generate DeepMIMO specific test sets: mobile and static variants.

Input:
- `test/data_<i>.npy` generated by `data_division.py`, each containing
  `choice_in_box` channel samples from one spatial box.

Output:
- `specifictest_mobile/`: random temporal-like sequences.
- `specifictest_static/`: sequences where one "present" sample is repeated,
  simulating near-static behavior.
"""

import os
import random

import numpy as np
from tqdm import tqdm


path = '../data/DeepMIMO/O1/32antx32car_3p5GHz_40MHz_R501-1400_V1_23-9-25'

np.random.seed(1)
random.seed(1)

choice_in_box = 32
test_box = 1000

# Number of sequences generated from each test box.
box_choice = 20

# Final sequence length used by the model.
sequence_length = 17


def build_mobile_sequences() -> None:
    """Generate mobile-style sequences by random sampling without repetition.

    Args:
        None

    Returns:
        None
    """
    output_dir = os.path.join(path, 'specifictest_mobile')
    os.makedirs(output_dir, exist_ok=True)

    for i in tqdm(range(test_box), desc='Building specifictest_mobile'):
        data = np.load(os.path.join(path, 'test', f'data_{i}.npy'))
        whole_index_list = list(range(choice_in_box))

        for j in range(box_choice):
            sampled_indices = random.sample(whole_index_list, sequence_length)
            new_data = data[sampled_indices]
            np.save(os.path.join(output_dir, f'data_{i * box_choice + j}.npy'), new_data)

    np.save(os.path.join(output_dir, 'data_len.npy'), test_box * box_choice)


def build_static_sequences() -> None:
    """Generate static-style sequences with repeated present-frame samples.

    Construction rule (length = 17):
    - First draw `sequence_length - 4` unique indices.
    - Treat the last sampled index as the present frame.
    - Repeat this present index 5 times in total within the final sequence.

    Args:
        None

    Returns:
        None
    """
    output_dir = os.path.join(path, 'specifictest_static')
    os.makedirs(output_dir, exist_ok=True)

    for i in tqdm(range(test_box), desc='Building specifictest_static'):
        data = np.load(os.path.join(path, 'test', f'data_{i}.npy'))
        whole_index_list = list(range(choice_in_box))

        for j in range(box_choice):
            sampled_indices = random.sample(whole_index_list, sequence_length - 4)

            history_indices = sampled_indices[:-1]   # 12 indices
            present_index = sampled_indices[-1]      # 1 index

            # Insert the present frame 4 extra times, then shuffle.
            history_indices.extend([present_index] * 4)
            random.shuffle(history_indices)

            # Append present frame once more so it appears 5 times in total.
            history_indices.append(present_index)

            new_data = data[history_indices]
            np.save(os.path.join(output_dir, f'data_{i * box_choice + j}.npy'), new_data)

    np.save(os.path.join(output_dir, 'data_len.npy'), test_box * box_choice)


def main() -> None:
    """Entry point for building both specific test sets."""
    build_mobile_sequences()
    build_static_sequences()


if __name__ == '__main__':
    main()
